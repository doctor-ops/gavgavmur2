function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function foldAccents(value: string): string {
  return value
    .replace(/[œŒ]/g, 'oe')
    .replace(/[æÆ]/g, 'ae')
    .normalize('NFD')
    .replace(/\p{M}/gu, '');
}

/** В части базы вместо é/è/à стоит знак «?». */
function questionAccents(value: string): string | null {
  let changed = false;
  let out = '';
  for (const ch of value) {
    if (ch === 'œ' || ch === 'Œ' || ch === 'æ' || ch === 'Æ') {
      changed = true;
      out += '?';
      continue;
    }
    const base = ch.normalize('NFD').replace(/\p{M}/gu, '');
    if (base !== ch) {
      changed = true;
      out += '?';
    } else {
      out += ch;
    }
  }
  return changed ? out : null;
}

const glossary = (() => {
  const sorted = Object.entries({ ...ingredientTranslations, ...extraTranslations })
    .map(([source, target]) => ({ source: source.toLowerCase(), target }))
    .filter((entry) => entry.source.length >= 2)
    .sort((a, b) => b.source.length - a.source.length);

  const seen = new Set<string>();
  const entries: Array<{ source: string; target: string; regex: RegExp }> = [];
  for (const entry of sorted) {
    const forms = [entry.source, questionAccents(entry.source), foldAccents(entry.source)];
    for (const form of forms) {
      if (!form || form.length < 2 || seen.has(form)) continue;
      seen.add(form);
      const keepsAcronym = entry.target.includes(`(${form.toUpperCase()})`);
      const boundary = keepsAcronym ? '(?<![\\p{L}\\p{N}(])' : '(?<![\\p{L}\\p{N}])';
      const end = keepsAcronym ? '(?![\\p{L}\\p{N})])' : '(?![\\p{L}\\p{N}])';
      entries.push({
        source: form,
        target: entry.target,
        regex: new RegExp(`${boundary}${escapeRegExp(form)}${end}`, 'giu'),
      });
    }
  }
  return entries;
})();

function decodeEntities(text: string): string {
  return text
    .replace(/&quot;/gi, ' ')
    .replace(/&amp;/gi, ' и ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&lt;/gi, ' ')
    .replace(/&gt;/gi, ' ');
}

function cutInstructions(text: string): string {
  const lower = text.toLowerCase();
  let end = text.length;
  for (const marker of cutMarkers) {
    const at = lower.indexOf(marker);
    if (at >= 0 && at < end) end = at;
  }
  return text.slice(0, end);
}

function expandAbbreviations(text: string): string {
  return text
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*12\b/gi, 'витамин B12')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*6\b/gi, 'витамин B6')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*5\b/gi, 'витамин B5')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*3\b/gi, 'витамин B3')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*2\b/gi, 'витамин B2')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*b-?\s*1\b/gi, 'витамин B1')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*d\s*3\b/gi, 'витамин D3')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*d\b/gi, 'витамин D')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*k\b/gi, 'витамин K')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*c\b/gi, 'витамин C')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*e\b/gi, 'витамин E')
    .replace(/\bvit(?:amin|amine|amina)?\.?\s*a\b/gi, 'витамин A')
    .replace(/\bmin\.?(?=\s*\d)/gi, 'не менее')
    .replace(/\bmax\.?(?=\s*\d)/gi, 'не более');
}

function applyGlossary(text: string): string {
  let result = text;
  for (const entry of glossary) {
    if (!result.toLowerCase().includes(entry.source)) continue;
    result = result.replace(entry.regex, entry.target);
  }
  return result;
}

function polish(text: string): string {
  let result = text
    .replace(/\b(composition|ingredients|ingrédients|ingredientes|zusammensetzung|состав)\b\s*[•.:]*/gi, '')
    .replace(/\b(?:par|per|pro|au)\s*kg\b/gi, 'на кг')
    .replace(/\b(and\/or|et\/ou)\b/gi, 'и/или')
    .replace(/\bkcal\b/gi, 'ккал')
    .replace(/(\d)\s*ul\b/gi, '$1 МЕ')
    .replace(/\bel\s*\((?=железо)/gi, 'e1 (')
    .replace(/\b(additifs?(?:\s+par\s+kg)?|additives?(?:\s+per\s+kg)?|nutritional additives|additifs nutritionnels)\s*:?\s*/gi, 'добавки: ')
    .replace(/\b(constituants analytiques|analytical constituents|analytische bestandteile|guaranteed analysis)\s*:?\s*/gi, 'аналитический состав: ')
    .replace(/(\d)\.(\d)/g, '$1,$2')
    .replace(/(\d)\s+%/g, '$1%')
    .replace(/[ \t]+/g, ' ')
    .replace(/\s+([,;:])/g, '$1')
    .replace(/([;:])(?=\S)/g, '$1 ')
    .replace(/,(?!\d)(?=\S)/g, ', ')
    .replace(/(?:,\s*){2,}/g, ', ')
    .replace(/\(\s+/g, '(')
    .replace(/\s+\)/g, ')')
    .trim();

  result = result.toLowerCase();
  for (const [pattern, replacement] of vitaminRestore) {
    result = result.replace(pattern, replacement);
  }
  result = result
    .replace(/(?<=\P{L}|^)(de|des|du|d'|of|et|and|und|avec|with|the|les|la|le|di|del|van|og|och|for|par|per|aux|au|en|dans|pour|by|in|or|to|as|from|un|une|on|est|son|sa|ses|votre|sous|der|den|het|een|med|av|y|für|fur|con|para|al)(?=\P{L}|$)/giu, ' ')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,;:])/g, '$1')
    .replace(/(?:,\s*){2,}/g, ', ')
    .trim();

  return result.replace(/^[,;:\s]+|[,;:\s]+$/g, '');
}

/** Переводит состав на русский и приводит запись к одному виду. */
export function normalizeComposition(text: string): string {
  const cleaned = cutInstructions(decodeEntities(text)).replace(/\s+/g, ' ').trim();
  if (!cleaned) return '';
  return polish(expandAbbreviations(applyGlossary(cleaned)));
}
